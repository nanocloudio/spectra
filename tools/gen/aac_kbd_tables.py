#!/usr/bin/env python3
"""Generate `modules/app/codec/audio/aac/kbd.rs` from the ISO formula.

WHY THIS EXISTS

The shipped table arrived in Spectra with the header "Extracted from
/tmp/faad2-src/libfaad/kbd_win.h", and faad2 is GPLv2. That made 22 KB of the
AAC path a licence question gating publication (T2.3.1, codec-inventory §2.1).

The question is answerable rather than arguable, because the Kaiser-Bessel
Derived window is *entirely determined* by a formula published in ISO/IEC
13818-7 and 14496-3. There is exactly one correct table for a given (N, alpha);
any correct implementation produces it. Measured against the shipped values:

    KBD_LONG_1024 (alpha=4):  941/1024 bit-identical as f32, rest 1 ulp
    KBD_SHORT_128 (alpha=6):  113/128  bit-identical as f32, rest 1 ulp

One ulp is the last-bit rounding difference between two correct evaluations of
the same expression — faad2 sums a Bessel series to its own tolerance, numpy
uses a different approximation. Nothing about the numbers is authored.

So rather than argue merger doctrine over a copied file, this regenerates the
table from the formula. The output is ours by construction, and the parity
suite proves the substitution changes no decoded output.

FORMULA (ISO/IEC 13818-7 §"Window shapes", identical in 14496-3)

    W(j)    = I0(pi * alpha * sqrt(1 - (2j/N - 1)^2)) / I0(pi * alpha)
    w_kbd[n] = sqrt( sum(W[0..n]) / sum(W[0..N]) )        n = 0 .. N-1

for the first half of a 2N-point window. AAC uses alpha = 4 for the long
window (N = 1024) and alpha = 6 for the short (N = 128).

USAGE
    python3 tools/gen/aac_kbd_tables.py            # print a diff summary
    python3 tools/gen/aac_kbd_tables.py --write    # rewrite the .rs file

`tests/harness/tests/aac_table_provenance.rs` re-derives the same values at
test time, so the claim above is checked on every run rather than trusted.
"""

import argparse
import subprocess
import pathlib
import re
import sys

try:
    import numpy as np
except ImportError:
    sys.exit("numpy is required: pip install numpy")

REPO = pathlib.Path(__file__).resolve().parents[2]
TARGET = REPO / "modules" / "app" / "codec" / "audio" / "aac" / "kbd.rs"

# (rust_name, N, alpha)
TABLES = [
    ("KBD_LONG_1024", 1024, 4.0),
    ("KBD_SHORT_128", 128, 6.0),
]


def kbd(n: int, alpha: float) -> np.ndarray:
    """First half (n points) of the 2n-point KBD window."""
    j = np.arange(n + 1, dtype=np.float64)
    x = 2.0 * j / n - 1.0
    kernel = np.i0(np.pi * alpha * np.sqrt(np.maximum(0.0, 1.0 - x * x))) / np.i0(
        np.pi * alpha
    )
    cumulative = np.cumsum(kernel)
    return np.sqrt(cumulative[:n] / cumulative[n])


def parse_existing(name: str, text: str) -> np.ndarray | None:
    m = re.search(rf"pub static {name}: \[f32; (\d+)\] = \[(.*?)\];", text, re.S)
    if not m:
        return None
    # Tolerate bare integers ("1") as well as decimals: the window ends at
    # exactly 1.0 and a previous generator emitted those without a point.
    vals = re.findall(r"-?\d+(?:\.\d+)?(?:[eE][-+]?\d+)?", m.group(2))
    return np.array([float(v) for v in vals], dtype=np.float64)


def ulp_diff(a: np.ndarray, b: np.ndarray) -> np.ndarray:
    a32, b32 = a.astype(np.float32), b.astype(np.float32)
    return np.abs(
        a32.view(np.int32).astype(np.int64) - b32.view(np.int32).astype(np.int64)
    )


def fmt(v: float) -> str:
    """Shortest round-tripping literal that Rust accepts as f32.

    `%.17g` renders 1.0 as "1", which rustc rejects as an integer where an
    f32 is expected — the window ends at exactly 1.0, so this is not a corner
    case, it is the last three entries of every table.
    """
    s = f"{v:.17g}"
    if "." not in s and "e" not in s and "E" not in s and "inf" not in s:
        s += ".0"
    return s


def render() -> str:
    out = [
        "// @generated by tools/gen/aac_kbd_tables.py — do not edit by hand.",
        "//",
        "// Kaiser-Bessel Derived analysis windows, computed from the formula in",
        "// ISO/IEC 13818-7 (identical in 14496-3):",
        "//",
        "//     W(j)     = I0(pi*alpha*sqrt(1 - (2j/N - 1)^2)) / I0(pi*alpha)",
        "//     w_kbd[n] = sqrt( sum(W[0..n]) / sum(W[0..N]) )",
        "//",
        "// alpha = 4 for the long window (N = 1024), 6 for the short (N = 128).",
        "//",
        "// These values are DETERMINED BY THE FORMULA, not authored: there is one",
        "// correct table per (N, alpha) and any correct implementation yields it.",
        "// That is what retires the faad2 provenance question this file used to",
        "// carry (codec-inventory §2.1) — see the generator's header, and",
        "// tests/harness/tests/aac_table_provenance.rs, which re-derives these at",
        "// test time so the claim is checked rather than asserted.",
        "",
    ]
    for name, n, alpha in TABLES:
        vals = kbd(n, alpha).astype(np.float32)
        out.append(f"pub static {name}: [f32; {n}] = [")
        # 8 per line, matching the source layout this replaces.
        for i in range(0, n, 8):
            chunk = ", ".join(fmt(v) for v in vals[i : i + 8])
            out.append(f"    {chunk},")
        out.append("];")
        out.append("")
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true", help="rewrite the .rs file")
    args = ap.parse_args()

    existing = TARGET.read_text() if TARGET.exists() else ""
    for name, n, alpha in TABLES:
        want = kbd(n, alpha)
        have = parse_existing(name, existing)
        if have is None:
            print(f"{name}: not present in {TARGET.name}")
            continue
        d = ulp_diff(have, want)
        identical = int((d == 0).sum())
        print(
            f"{name}: {identical}/{n} bit-identical as f32, "
            f"max {d.max()} ulp, mean {d.mean():.3f} ulp"
        )
        if d.max() > 1:
            print(f"  WARNING: {name} differs by more than 1 ulp — investigate "
                  f"before regenerating; that is not just rounding.")
            return 1

    if args.write:
        TARGET.write_text(render())
        # Run rustfmt over the result. `modules/**` is fmt-checked directly by
        # `fluxor ci` phase 1.1 now that the project has no root manifest, so a
        # generator that emits unformatted Rust breaks the gate every time it is
        # run — and the breakage lands on whoever regenerates next, not on
        # whoever wrote the generator.
        fmt = subprocess.run(
            ["rustfmt", "--edition", "2021", str(TARGET)],
            capture_output=True,
            text=True,
            check=False,
        )
        if fmt.returncode != 0:
            print(f"rustfmt failed on {TARGET.name}:\n{fmt.stderr}")
            return 1
        print(f"wrote {TARGET.relative_to(REPO)} (rustfmt-clean)")
    else:
        print("(dry run — pass --write to regenerate)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
